def meaning(component,name,label):
    if component=='randomUI':
        import re
        m=re.fullmatch(r'(rot|scl|mov)([XYZ])(Min|Max)Spin',name)
        if m:return m[3]+'imum random '+{'rot':'rotation in degrees','scl':'scale multiplier','mov':'movement in scene units'}[m[1]]+' on '+m[2]+'. The opposite endpoint stays ordered.'
        if name in ('wholeMinSpin','wholeMaxSpin'):return ('Minimum' if name=='wholeMinSpin' else 'Maximum')+' whole-object random scale multiplier; preserves proportions.'
    if component=='interactionsUI' and name in ('strengthSpin','gapSpin'):
        return {'strengthSpin':'Amount of broad Bend response.','gapSpin':'Bending clearance from the collider; independent of Hide margin.'}[name]
    if component=='collidersUI' and name in ('addButton','removeButton'):
        return 'Pick a scene collider node.' if name=='addButton' else 'Unlink the highlighted scene collider; keep its scene geometry.'
    if name.startswith('edgeRot'):return 'Edge Row orientation adjustment around '+name[7]+' in degrees.'
    return MEANINGS.get(name)
