"""A creation-order witness through actual generated controls; no pointer automation."""
from pathlib import Path
import sys,traceback
sys.path.insert(0,str(Path(__file__).resolve().parent))
from common import *
rec=Recorder('workflow')
try:
    r.CyrusStopBrush();r.resetMaxFile(r.Name('noPrompt'))
    r.units.SystemType=r.Name('Centimeters');r.units.SystemScale=1
    ground=r.plane(name='Workflow receiver',width=1200,length=900,widthsegs=8,lengthsegs=8)
    other=r.plane(name='Second receiver',width=600,length=900,pos=pt(1000,0))
    model=r.box(name='Workflow model',width=8,length=8,height=24,pos=pt(2400,0))
    r.hide(model)
    node=rec.step('Create empty Scatter',lambda:r.AminScatterObject(name='Workflow Scatter'))
    root=node.baseObject;root.updateMode=1;root.autoRender=False
    rec.step('Open empty Modify layout',lambda:activate(node,'layersUI'))
    rec.step('Add first layer',root.newLayer)
    leaf=root.selectedLayer();leaf.amount=5000
    rec.step('Assign first receiver',lambda:root.setLayerSurfaces(leaf,arr([ground])))
    panel=activate(node,'modelsUI')
    rec.step('Add Point using generated button',panel.sourceUI_addPoint.pressed)
    rec.step('Explicit first Update',lambda:update(root))
    rec.check(len(root.groupSnapshotRows[0])==5000,'First Point layer produces requested candidates')
    original=fingerprint(root)
    rec.step('Replace Point using actual picker handler',lambda:panel.sourceUI_replacePoint.picked(model))
    rec.step('Update Point replacement',lambda:update(root))
    rec.check(fingerprint(root)==original,'Point replacement preserves placement identity and transforms')
    rec.step('Add second layer',root.newLayer)
    second=root.selectedLayer();second.amount=1700
    rec.step('Assign second layer receiver',lambda:root.setLayerSurfaces(second,arr([other])))
    panel=activate(node,'modelsUI');rec.step('Add Point to second layer',panel.sourceUI_addPoint.pressed)
    rec.step('Update both layers',lambda:update(root))
    rec.check(fingerprint(root)[0]==original[0],'Point layer preserves first geometry layer')
    rec.step('Remove Point layer',lambda:root.removeLogicalLayer(second))
    rec.step('Update after removal',lambda:update(root))
    rec.check(fingerprint(root)==original,'Removing second layer restores exact first-layer publication')
    root.selectLayer(1);leaf=root.selectedLayer()
    rec.step('Switch to Mesh',lambda:root.setGroupDisplay(3))
    rec.step('Return to Centres',lambda:root.setGroupDisplay(4))
    area=r.rectangle(name='Include border',width=1000,length=720)
    hole=r.circle(name='Exclude hole',radius=100)
    panel=activate(node,'areasUI')
    rec.step('Pick Include boundary',lambda:panel.areaUI_pickArea.picked(area))
    rec.step('Pick Exclude boundary',lambda:panel.areaUI_pickArea.picked(hole))
    panel.areaUI_areaMode.changed(2)
    rec.step('Update Include and Exclude',lambda:update(root))
    rows=list(root.groupSnapshotRows[0])
    rec.check(all(abs(float(x[0].row4.x))<=500.01 and abs(float(x[0].row4.y))<=360.01 for x in rows),'Include clips all positions')
    rec.check(all(float(r.length(pt(x[0].row4.x,x[0].row4.y)))>=99.9 for x in rows),'Exclude hole remains empty')
    cfg=arr([False,0.,True,100.,arr([.2,1.]),True,100.,arr([0.,1.])])
    rec.step('Set independent scale and density falloff',lambda:leaf.setFallConfig(area,cfg))
    rec.step('Update falloff',lambda:update(root))
    rec.check(any(float(r.length(x[0].row1))<.99 for x in root.groupSnapshotRows[0]),'Scale falloff reaches transforms')
    painted=rec.step('Create receiver-bound Paint Area',lambda:root.addPaintArea(leaf,target=ground))
    r.cyrusBrushSettings(painted.paintDocument,210.,False)
    rec.step('Paint first connected patch',lambda:r.cyrusBrushDab(painted.paintDocument,pt(-200,0,900),pt(0,0,-1),True))
    rec.step('Update painted patch',lambda:update(root));fp=fingerprint(root)
    rec.step('Paint identical patch again',lambda:r.cyrusBrushDab(painted.paintDocument,pt(-200,0,900),pt(0,0,-1),True))
    rec.step('Update repeated paint',lambda:update(root))
    rec.check(fingerprint(root)==fp,'Repeated paint unions coverage without extra instances')
    r.cyrusBrushSettings(painted.paintDocument,55.,True)
    rec.step('Erase pocket',lambda:r.cyrusBrushDab(painted.paintDocument,pt(-200,0,900),pt(0,0,-1),True))
    rec.step('Update erase',lambda:update(root))
    rec.check(all(float(r.distance(x[0].row4,pt(-200,0)))>=54.8 for x in root.groupSnapshotRows[0]),'Erase creates a real unplanted pocket')
    before=state();rec.step('Browse controls without editing',lambda:[activate(node,page) for page in ('modelsUI','coverageUI','areasUI','layoutUI','layersUI')])
    rec.check(fingerprint(root)==before['controllers'][0]['fingerprints'],'Browsing retains exact placements')
    rec.check(int(root.procEpoch)==before['controllers'][0]['epoch'],'Browsing does not republish placements')
    leaf.paintEnabled=False;leaf.areaNodes=arr([]);leaf.areaModes=arr([]);root.refreshAll()
    rec.step('Save completed workflow witness',lambda:r.saveMaxFile(str(OUT/'Workflow.max'),quiet=True),redraw=False)
except Exception:rec.error(traceback.format_exc())
