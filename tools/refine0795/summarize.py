"""Build compact, reproducible campaign evidence from passive host receipts."""
from pathlib import Path
import hashlib,json,statistics
ROOT=Path(__file__).resolve().parents[2]
DOC=ROOT/'docs/Terrace_Workflow_0.79.5_2026-10-11';DOC.mkdir(exist_ok=True)
def read(p): return json.loads(p.read_text(encoding='utf-8'))
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
evidence=dict(version='0.79.5',schema=55,hosts={},baseline={},delivery={},limitations=[
    'Scripted elapsed redraw is not presented FPS or physical latency.',
    'Process memory and conservative native reservations are not measured VRAM.',
    'Controls mapped/bound does not mean every physical action was exercised.',
    'No normal-profile installation, Git push or website changes in this campaign.'])
names=['regressions','display0792','invalidation0792','layer-lifecycle','point-model-probe',
    'scene-results','falloff-results','points-results','reopen-results','empty-results','layout-results',
    'reuse-checks','endurance','navigation0792','workflow','garden-checks','garden-reopen',
    'controls','render','benchmark','garden-refinement','final-scene','final-render','ui-timing']
for year in (2026,2027):
    host=ROOT/f'build/mcp-qualification/refine0795-final-{year}-01'
    data=dict(launch=read(host/'launch.json'),receipts={},native_tests=dict(count=24,
        log=str(ROOT/f'build/refine0795-20261011/max{year}-02/tests.log')))
    loaded=host/'loaded-modules.json'
    if loaded.exists(): data['loaded_modules']=read(loaded)
    for name in names:
        p=host/(name+'.json')
        if not p.exists(): continue
        d=read(p);checks=d.get('assertions',d.get('checks',[]))
        item=dict(path=str(p),sha256=sha(p),errors=d.get('errors',[]))
        if isinstance(checks,list): item['checks']=checks
        for key in ('failures','mesh_color_uploads','point_color_uploads','render_ms','scene','image','layers','native_error','median_warm_ms'):
            if key in d:item[key]=d[key]
        if name=='benchmark':
            item['metrics']={k:d[k] for k in ('navigation','local-color','unchanged-display')}
            item['population']=[dict(accepted=l['accepted'],shown=l['shown']) for l in d['checkpoints'][0]['before']['controllers'][0]['layers']]
        if name=='endurance':
            states=[c['state'] for c in d['cycles']]
            item['memory_private_range']=[min(s['memory']['private'] for s in states),max(s['memory']['private'] for s in states)]
            item['resource_samples']=[dict(cycle=c['cycle'],retained=c['state']['controllers'][0]['retained'],mesh=c['state']['controllers'][0]['mesh']) for c in d['cycles']]
        if name=='controls':item['presentation_count']=len(d['controls']);item['semantic_count']=d['semantic_controls']
        if name=='navigation0792':
            item['measurements']=[{k:m[k] for k in ('label','held','samples_ms','median_ms')} for m in d['measurements']]
            item['records']=d['records']
        if name in ('workflow','ui-timing'):item['timings']=[{k:c[k] for k in ('label','action_ms','redraw_ms')} for c in d['checkpoints']]
        data['receipts'][name]=item
    for kind,phases in [('layer-undo',('prepare','delete','undo','redo')),('radius-undo',('prepare','edit','undo','redo'))]:
        for phase in phases:
            p=host/(kind+'-'+phase+'.json');data['receipts'][p.stem]=dict(path=str(p),sha256=sha(p),result=read(p))
    evidence['hosts'][str(year)]=data
    p=DOC/f'package-{year}.json'
    if p.exists():evidence['delivery'][str(year)]=read(p)
base=ROOT/'build/mcp-qualification/refine0795-baseline-2027-01'
evidence['baseline']['launch']=read(base/'launch.json')
for name in ('benchmark','display-scope','garden-build'):
    p=base/(name+'.json');d=read(p);item=dict(path=str(p),sha256=sha(p))
    if name=='benchmark':item['metrics']={k:d[k] for k in ('navigation','local-color','unchanged-display')}
    evidence['baseline'][name]=item
evidence['generated_check']=read(ROOT/'build/refine0795-20261011/generated-final/generated-check.json')
import xml.etree.ElementTree as ET
pytest=ROOT/'build/refine0795-20261011/pytest-final.xml'
evidence['python_tests']=dict(path=str(pytest),sha256=sha(pytest),suites=[e.attrib for e in ET.parse(pytest).getroot().findall('testsuite')])
artifacts=ROOT/'Test Scene/Terraced_Garden_0795'
evidence['scene_artifacts']=[dict(path=str(p),sha256=sha(p),bytes=p.stat().st_size) for p in artifacts.iterdir() if p.suffix.lower() in ('.max','.png','.md')]
(DOC/'evidence.json').write_text(json.dumps(evidence,indent=2)+'\n',encoding='utf-8')
catalog=read(ROOT/'CyrusMCP/cyrus_mcp/feature-catalog.json')
bound=read(ROOT/'build/mcp-qualification/refine0795-final-2027-01/controls.json')['controls']
seen={c['semantic'] for c in bound if not c['missing']}
lines=['# Current control register — 0.79.5','',
    'Generated by `tools/refine0795/summarize.py`. All 241 semantic controls are listed. The 12 main sections expose 285 generated presentation bindings; all bound in Max 2027. Some semantic controls live in the controller, popup or container views, so they do not have a main-section binding. Bounds checks cover four selected sections on both hosts. Physical input remains unqualified for every row. See [feature coverage](COVERAGE.md) for functional witnesses; binding alone is not functional certification.','',
    '| Semantic control | Kind | Owner | Features | Main binding | Physical |',
    '| --- | --- | --- | --- | --- | --- |']
for c in catalog['controls']:
    semantic=c['section']+'.'+c['name'];mapped='[x] Bound' if semantic in seen else 'Other view / not captured'
    lines.append('| '+ ' | '.join([semantic,c['kind'],c['owner_context'],', '.join(c['capabilities']),mapped,'[ ] Open'])+' |')
(DOC/'CONTROL_REGISTER.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
# Keep full control bounds/captions alongside the summary; they are small and contain no secrets.
(DOC/'control-bindings.json').write_text(json.dumps(bound,indent=2)+'\n',encoding='utf-8')
print('Wrote compact evidence and control register')
