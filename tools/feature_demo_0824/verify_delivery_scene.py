"""Verify the final editable file after preview rendering; do not resave it."""
from pathlib import Path
import hashlib,json
from pymxs import runtime as r
OUT=Path(str(r.MCPFixtureDir)).resolve();assert OUT.name.startswith('foundation-roadmap-feature-demo0824-')
original=json.loads((OUT/'demo-verification.json').read_text());assert original['status']=='passed'
path=OUT/'CyrusScatter 0.82.4 Feature Demo.max';before=hashlib.sha256(path.read_bytes()).hexdigest()
r.loadMaxFile(str(path),quiet=True,useFileUnits=True)
root=r.getNodeByName('CYRUS 0.82.4 | SELECT ME - five feature layers').baseObject;root.refreshAll();r.CyrusPointSync()
def vector(v):return tuple(float(v[k]) for k in range(3))
rows=[{str(row[2]):(tuple(vector(getattr(row[0],'row'+str(i))) for i in range(1,5)),
    int(row[1]),str(row[2]),int(row[3]),vector(row[4]),int(row[5]),bool(row[6]),int(row[7])) for row in group}
    for group in root.groupSnapshotRows]
fingerprint=hashlib.sha256(json.dumps(rows,sort_keys=True,separators=(',',':')).encode()).hexdigest()
assert fingerprint==original['final_publication_sha256']
assert len(root.layerObjects)==5 and all(not bool(leaf.dirty) and not str(leaf.previewError) for leaf in root.layerObjects)
assert int(root.updateMode)==1
assert not [n for n in r.objects if str(n.name).startswith('TEMP PREVIEW')]
assert len([n for n in r.objects if str(r.classOf(n))=='Pyramid'])==6
camera=r.viewport.getCamera();assert camera==r.getNodeByName('CAM 01 | Overview')
assert hashlib.sha256(path.read_bytes()).hexdigest()==before
previews={name:hashlib.sha256((OUT/name).read_bytes()).hexdigest() for name in ['Preview - Overview.png','Preview - Plane.png','Preview - Mountain.png','Preview - Top.png']}
assert len(set(previews.values()))==4
assets=r.getMAXFileAssetMetadata(str(path));assert len(assets)==0,'Unexpected external asset dependency'
result={'status':'passed','version':'0.82.4','max_year':2027,'scene':str(path),'scene_sha256':before,
    'bytes':path.stat().st_size,'assertions':len(original['checks']),'counts':original['counts'],'total_accepted':original['total_accepted'],
    'publication_sha256':fingerprint,'saved_camera':str(camera.name),'external_assets':len(assets),
    'contains_temporary_preview_meshes':False,'all_five_full_row_publications_restored':True,
    'preview_method':'Temporary Scanline snapshots generated by MAXScript from the exact accepted rows; editable scene file is unchanged. No native renderer-parity qualification is implied.',
    'previews':previews,'computer_use_used':False,'plugin_code_changed':False,'phase6':'paused'}
(OUT/'demo-delivery-scene.json').write_text(json.dumps(result,indent=2)+'\n')
